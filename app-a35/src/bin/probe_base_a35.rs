//! Minimal position-independent A35 probe for vendor ATF DRAM window.

#![no_std]
#![no_main]
#![allow(named_asm_codepoint)]

use core::arch::global_asm;

global_asm!(
    ".section .text.start",
    ".global _start",
    "_start:",
    "movz x2, #0x0000",
    "movk x2, #0x3009, lsl #16",
    "movk x2, #0x4, lsl #32",
    "mov x20, x2",
    "movz x21, #0x3B14",
    "movk x21, #0x14C3, lsl #16",
    "movz x22, #0x3B00",
    "movk x22, #0x14C3, lsl #16",
    "mov w0, #0x30",
    "bl send_byte",
    "movz w3, #0xCA35",
    "movk w3, #0xCA35, lsl #16",
    "str w3, [x20]",
    "mov w0, #0x43",
    "bl send_byte",
    "movz w3, #0xEEF0",
    "movk w3, #0xA35B, lsl #16",
    "str w3, [x20, #4]",
    "mov w0, #0x48",
    "bl send_byte",
    "movz w3, #0x0001",
    "str w3, [x20, #8]",
    "mrs x4, CurrentEL",
    "str w4, [x20, #12]",
    "mrs x4, DAIF",
    "str w4, [x20, #16]",
    "mrs x4, SPsel",
    "str w4, [x20, #20]",
    "mrs x4, NZCV",
    "str w4, [x20, #24]",
    "mrs x4, CurrentEL",
    "cmp x4, #0xC",
    "b.eq 3f",
    "cmp x4, #0x8",
    "b.eq 4f",
    "cmp x4, #0x4",
    "b.eq 5f",
    "b 6f",
    "3:",
    "mrs x5, SCTLR_EL3",
    "str w5, [x20, #32]",
    "mrs x5, SCR_EL3",
    "str w5, [x20, #36]",
    "mrs x5, VBAR_EL3",
    "str w5, [x20, #40]",
    "b 6f",
    "4:",
    "mrs x5, SCTLR_EL2",
    "str w5, [x20, #32]",
    "mrs x5, HCR_EL2",
    "str w5, [x20, #36]",
    "mrs x5, VBAR_EL2",
    "str w5, [x20, #40]",
    "b 6f",
    "5:",
    "mrs x5, SCTLR_EL1",
    "str w5, [x20, #32]",
    "mrs x5, VBAR_EL1",
    "str w5, [x20, #40]",
    "6:",
    "movz w3, #0x0002",
    "str w3, [x20, #8]",
    "mov w0, #0x53",
    "bl send_byte",
    "1:",
    "mov w0, #0x41",
    "bl send_byte",
    "b 1b",
    "send_byte:",
    "movz x23, #0xFFFF",
    "2:",
    "ldr w3, [x21]",
    "str w3, [x20, #28]",
    "tbnz w3, #5, 7f",
    "subs x23, x23, #1",
    "b.ne 2b",
    "ret",
    "7:",
    "str w0, [x22]",
    "ret",
);

#[panic_handler]
fn panic(_: &core::panic::PanicInfo) -> ! {
    loop {
        unsafe { core::arch::asm!("wfe") }
    }
}
